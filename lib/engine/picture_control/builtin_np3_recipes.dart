  static BuiltinNp3Seed _makeSeed({
    required String id,
    required String cameraName,
    required String noteNameZh,
    required String descriptionZh,
    required String recommendedSceneId,
    required PictureControlCategory category,
    required PictureControlBase base,
    required int sharpeningQ,
    required int midSharpeningQ,
    required int clarityQ,
    required int contrastQ,
    required int brightnessQ,
    int? saturationQ,
    int? hueQ,
    int monoFilter = 0,
    int monoToning = 0,
    int monoToningSaturation = 0,
    List<PictureControlCurvePoint>? curvePoints,
  }) {
    final hasCurve = curvePoints != null && curvePoints.length >= 2;
    final curveBlock =
        hasCurve ? Np3Codec.buildCurveBlockFromPoints(curvePoints) : null;
    final tempRecipe = PictureControlRecipe(
      format: PictureControlFormat.np3Standard,
      cameraName: cameraName,
      base: base,
      sharpeningQuarters: sharpeningQ,
      midRangeSharpeningQuarters: midSharpeningQ,
      clarityQuarters: clarityQ,
      contrastQuarters: contrastQ,
      brightnessQuarters: brightnessQ,
      saturationQuarters: saturationQ,
      hueQuarters: hueQ,
      monoFilter: monoFilter,
      monoToning: monoToning,
      monoToningSaturation: monoToningSaturation,
      hasCustomCurve: hasCurve,
      curvePoints: curvePoints ?? const [],
      rawCurveBlock: curveBlock,
    );
    final bytes = Np3Codec.encodeNp3File(tempRecipe);
    final parsed = Np3Codec.parse(bytes);
    return BuiltinNp3Seed(
      id: id,
      cameraName: parsed.cameraName,
      noteNameZh: noteNameZh,
      descriptionZh: descriptionZh,
      recommendedSceneId: recommendedSceneId,
      category: category,
      recipe: parsed,
      np3Bytes: bytes,
    );
  }

