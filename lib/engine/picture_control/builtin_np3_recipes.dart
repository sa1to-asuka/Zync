/// 优化校准配方分类枚举。
enum PictureControlCategory {
  all,
  portrait,
  landscape,
  street,
  vintage,
  cinema,
  airy,
  night,
  mono;

  String get labelZh => switch (this) {
        PictureControlCategory.all => '全部',
        PictureControlCategory.portrait => '人像写真',
        PictureControlCategory.landscape => '风光自然',
        PictureControlCategory.street => '街拍纪实',
        PictureControlCategory.vintage => '胶片复古',
        PictureControlCategory.cinema => '电影感',
        PictureControlCategory.airy => '日系清新',
        PictureControlCategory.night => '城市夜景',
        PictureControlCategory.mono => '经典黑白',
      };
}

/// 预览样片场景定义（支持 PicUI 图床远程高精图与内置本地 fallback）。
class PictureControlSampleScene {
  final String id;
  final String assetPath;
  final String? remoteUrl;
  final String labelZh;
  final String sourceName;

  const PictureControlSampleScene({
    required this.id,
    required this.assetPath,
    this.remoteUrl,
    required this.labelZh,
    required this.sourceName,
  });
}

/// 内置初始 NP3 配方定义。
class BuiltinNp3Seed {
  final String id;
  final String cameraName;
  final String noteNameZh;
  final String descriptionZh;
  final String recommendedSceneId;
  final PictureControlCategory category;
  final PictureControlRecipe recipe;
  final Uint8List np3Bytes;

  const BuiltinNp3Seed({
    required this.id,
    required this.cameraName,
    required this.noteNameZh,
    required this.descriptionZh,
    required this.recommendedSceneId,
    this.category = PictureControlCategory.all,
    required this.recipe,
    required this.np3Bytes,
  });
}

